import {readFile,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
let html=await readFile(resolve(root,'dist/client/index.html'),'utf8');
const script=html.match(/<script[^>]*src="([^"]+)"[^>]*><\/script>/);
const style=html.match(/<link[^>]*href="([^"]+\.css)"[^>]*>/);
if(!script||!style)throw Error('Expected bundled script and stylesheet');
const js=await readFile(resolve(root,'dist/client',script[1].replace(/^\//,'')),'utf8');
const css=await readFile(resolve(root,'dist/client',style[1].replace(/^\//,'')),'utf8');
html=html.replace(script[0],()=>`<script type="module">${js.replace(/<\/script/gi,'<\\/script')}</script>`).replace(style[0],()=>`<style>${css}</style>`);
const target=resolve(root,'..','model-training-tour.html');
await writeFile(target,html);
console.log(JSON.stringify({file:target,bytes:Buffer.byteLength(html),externalRuntimeDependencies:0}));
